"""
Build theta-scaled real term-premium counterfactual VAR datasets.

This is a robustness builder. It does not overwrite data/var_dataset.csv.
The inflation AR(1) is used first to construct real yields; the EH forecast
below is a real-rate forecast, not a nominal-rate/inflation forecast.

Economic construction:

    y_10_obs,t   = observed real 10-year yield from the active AR(1)-matched
                   Fisher decomposition.
    y_10_EH,t    = expectations-hypothesis 10-year real yield, computed as the
                   average expected path of future one-year real bill yields.
                   The forecast is generated by one baseline state VAR,
                   estimated once on (cape, observed spr, y_1).
    TP_t         = y_10_obs,t - y_10_EH,t.
    y_10_theta,t = y_10_EH,t + theta * TP_t.

For each theta, the script recomputes:

    spr_theta,t = y_10_theta,t - y_1,t
    xb_theta,t  = r_10_theta,t - y_1,t-1

using the same 10-year constant-maturity bond-return formula as the active
baseline.

Usage:

    python data/build_var_dataset_term_premium_scale.py
    python data/build_var_dataset_term_premium_scale.py --theta 0 0.5 1

Outputs:

    data/term_premium_scaling/var_dataset_theta_0p00.csv
    data/term_premium_scaling/var_dataset_theta_0p25.csv
    ...
    data/term_premium_scaling/term_premium_components.csv
    data/term_premium_scaling/term_premium_scaling_diagnostics.csv
    data/term_premium_scaling/term_premium_scaling_moments.csv
    data/term_premium_scaling/short_rate_sensitivity.csv
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from build_var_dataset_ar1_10y import (
    HERE,
    N_BOND,
    SAMPLE_END,
    SAMPLE_START,
    build as build_active_baseline,
    build_full_table as build_active_full_table,
    sharpe_jensen,
)


OUT_DIR = HERE / "term_premium_scaling"
DEFAULT_THETAS = (0.0, 0.25, 0.50, 0.75, 1.0)
DEFAULT_SENSITIVITY_RHOS = (0.70, 0.80, 0.90, 0.95)
STATE_COLS = ("cape", "spr", "y_1")


def theta_label(theta: float) -> str:
    """File-safe theta label, e.g. 0.25 -> 0p25."""
    label = f"{theta:.2f}".replace("-", "m").replace(".", "p")
    return label


def assert_contiguous_year_index(series: pd.Series, label: str) -> None:
    """Fail if a dropped NaN would make adjacent iloc rows non-adjacent years."""
    idx = series.index.to_numpy()
    if len(idx) == 0:
        return
    expected = np.arange(int(idx[0]), int(idx[0]) + len(idx))
    if not np.array_equal(idx.astype(int), expected):
        missing = sorted(set(expected.tolist()) - set(idx.astype(int).tolist()))
        raise ValueError(
            f"{label} index is not contiguous over {idx[0]}-{idx[-1]}; "
            f"missing years include {missing[:5]}"
        )


def eh_multiplier(rho: float, n: int) -> float:
    """AR(1) expectations-hypothesis multiplier for horizons j=0,...,n-1."""
    if abs(1.0 - rho) < 1e-10:
        return 1.0
    return float((1.0 - rho**n) / (n * (1.0 - rho)))


def fit_short_rate_ar1(y_1: pd.Series, *, mean_pinned: bool = True) -> dict[str, float]:
    """Mean-pinned AR(1) for the real one-year bill yield.

    The fitted law is:

        y_1,t+1 - mu = rho * (y_1,t - mu) + u_t+1.

    The default pins mu to the sample mean. This matches the downstream VAR
    convention used by lifecycle.var's constrained estimator. It intentionally
    differs from the unrestricted OLS inflation AR(1) in the active baseline:
    the short-rate AR(1) is only a parsimonious EH-yield device, and mean
    pinning keeps its unconditional short-rate level aligned with the VAR data.
    """
    s = y_1.dropna().astype(float)
    if len(s) < 5:
        raise ValueError("Need at least five observations to estimate AR(1).")
    assert_contiguous_year_index(s, "short-rate AR(1) sample")

    x = s.iloc[:-1].to_numpy()
    y = s.iloc[1:].to_numpy()
    if mean_pinned:
        mu = float(s.mean())
        x_d = x - mu
        y_d = y - mu
        denom = float(x_d @ x_d)
        if denom <= 0.0:
            raise ValueError("Short-rate series has zero variance.")
        rho = float((x_d @ y_d) / denom)
        intercept = (1.0 - rho) * mu
        resid = y_d - rho * x_d
        estimator = "mean_pinned"
    else:
        rho = float(np.cov(y, x, ddof=1)[0, 1] / np.var(x, ddof=1))
        intercept = float(y.mean() - rho * x.mean())
        mu = float(intercept / (1.0 - rho)) if abs(1.0 - rho) > 1e-10 else float(s.mean())
        resid = y - intercept - rho * x
        estimator = "ols"
    sigma = float(resid.std(ddof=1))
    return {
        "mu": mu,
        "rho": rho,
        "intercept": intercept,
        "sigma": sigma,
        "nobs": len(s),
        "sample_start": int(s.index.min()),
        "sample_end": int(s.index.max()),
        "estimator": estimator,
        "eh_multiplier": eh_multiplier(rho, N_BOND),
    }


def fixed_rho_short_rate_ar1(y_1: pd.Series, rho: float) -> dict[str, float]:
    """Short-rate expectation rule with externally fixed persistence."""
    s = y_1.dropna().astype(float)
    if len(s) < 5:
        raise ValueError("Need at least five observations for fixed-rho rule.")
    assert_contiguous_year_index(s, "fixed-rho short-rate sample")
    mu = float(s.mean())
    rho = float(rho)
    return {
        "mu": mu,
        "rho": rho,
        "intercept": (1.0 - rho) * mu,
        "sigma": float("nan"),
        "nobs": len(s),
        "sample_start": int(s.index.min()),
        "sample_end": int(s.index.max()),
        "estimator": "fixed_rho",
        "eh_multiplier": eh_multiplier(rho, N_BOND),
    }


def estimate_state_var_for_eh(full: pd.DataFrame) -> dict[str, object]:
    """Estimate the baseline state VAR used to forecast future real short rates.

    This VAR is estimated once from the empirical baseline state
    ``(cape, spr_obs, y_1)`` over the active 1920-2011 sample. The resulting
    coefficients are then held fixed when constructing every theta dataset.
    """
    sample = full.loc[SAMPLE_START:SAMPLE_END, list(STATE_COLS)].dropna().astype(float)
    if len(sample) < 10:
        raise ValueError("Need at least ten observations to estimate state VAR.")
    assert_contiguous_year_index(sample.iloc[:, 0], "state VAR EH sample")

    z_bar = sample.mean(axis=0).to_numpy()
    Zd = sample.to_numpy() - z_bar
    Y = Zd[1:, :]
    X = Zd[:-1, :]
    coeffs, *_ = np.linalg.lstsq(X, Y, rcond=None)
    Phi = coeffs.T
    const = (np.eye(len(STATE_COLS)) - Phi) @ z_bar
    resid = Y - X @ coeffs
    dof = Y.shape[0] - X.shape[1]
    if dof <= 0:
        raise ValueError("Not enough observations for state VAR degrees of freedom.")
    Sigma = (resid.T @ resid) / dof
    eigvals = np.linalg.eigvals(Phi)
    return {
        "method": "baseline_state_var",
        "state_cols": tuple(STATE_COLS),
        "z_bar": z_bar,
        "Phi": Phi,
        "const": const,
        "Sigma": Sigma,
        "max_abs_eig": float(np.max(np.abs(eigvals))),
        "nobs": len(sample),
        "sample_start": int(sample.index.min()),
        "sample_end": int(sample.index.max()),
        "y1_index": STATE_COLS.index("y_1"),
    }


def expected_average_short_rate_state_var(
    full: pd.DataFrame,
    state_var: dict[str, object],
    n: int,
) -> pd.Series:
    """Average VAR-implied expected real short rate over horizons j=0,...,n-1."""
    cols = list(state_var["state_cols"])
    Phi = np.asarray(state_var["Phi"], dtype=float)
    z_bar = np.asarray(state_var["z_bar"], dtype=float)
    y1_idx = int(state_var["y1_index"])

    state = full[cols].astype(float)
    valid = state.notna().all(axis=1).to_numpy()
    out = np.full(len(state), np.nan, dtype=float)
    if np.any(valid):
        Zc = state.to_numpy()[valid] - z_bar
        acc = np.zeros(int(valid.sum()), dtype=float)
        Phi_pow = np.eye(len(cols))
        for _h in range(n):
            forecast_h = z_bar + Zc @ Phi_pow.T
            acc += forecast_h[:, y1_idx]
            Phi_pow = Phi_pow @ Phi
        out[valid] = acc / n
    return pd.Series(out, index=full.index, name=f"y_{n}_real_EH")


def expected_average_short_rate(
    y_1: pd.Series,
    short_ar1: dict[str, float],
    n: int,
) -> pd.Series:
    """Average expected future short rate over horizons j=0,...,n-1."""
    rho = float(short_ar1["rho"])
    mu = float(short_ar1["mu"])
    multiplier = eh_multiplier(rho, n)
    out = mu + multiplier * (y_1.astype(float) - mu)
    return out.rename(f"y_{n}_real_EH")


def constant_maturity_return_from_log_yield(
    y_n_log: pd.Series,
    n: int,
) -> tuple[pd.Series, pd.Series]:
    """Campbell-Lo-MacKinlay-style constant-maturity return from log yields."""
    y_n_log = y_n_log.astype(float)
    gross_yield = np.exp(y_n_log)
    denom = 1.0 - gross_yield.pow(-1)
    raw_duration = (1.0 - gross_yield.pow(-n)) / denom
    duration = raw_duration.where(denom.abs() > 1e-10, float(n)).rename("duration")
    r_next = duration * y_n_log - (duration - 1.0) * y_n_log.shift(-1)
    return r_next.shift(1).rename("r_n_real"), duration


def build_full_yield_table() -> tuple[pd.DataFrame, dict[str, float], dict[str, object]]:
    """Build the active real-yield table with extra pre-sample rows.

    The active output sample starts in 1920, but the bond return in 1920 needs
    the 1919 long yield. The raw timing and return construction come directly
    from data/build_var_dataset_ar1_10y.py to avoid drift.
    """
    df, inflation_ar1 = build_active_full_table()
    df = df.copy()
    df["y_n_real_obs"] = df["y_n_real"]

    state_var = estimate_state_var_for_eh(df)
    df["y_n_real_EH"] = expected_average_short_rate_state_var(df, state_var, N_BOND)
    df["term_prem"] = df["y_n_real_obs"] - df["y_n_real_EH"]

    return df, inflation_ar1, state_var


def short_rate_sensitivity_table(
    full: pd.DataFrame,
    baseline_state_var: dict[str, object],
    sensitivity_rhos: tuple[float, ...],
) -> pd.DataFrame:
    """Diagnostics for alternative short-rate expectation rules.

    These diagnostics bound how much the EH yield and residual term-premium
    component move when the short-rate persistence assumption changes. They do
    not write lifecycle-ready datasets; the theta datasets use the baseline
    state-VAR EH construction.
    """
    sample = full.loc[SAMPLE_START:SAMPLE_END].copy()
    rows = []

    y_eh_state = expected_average_short_rate_state_var(sample, baseline_state_var, N_BOND)
    eh_spread_state = y_eh_state - sample["y_1"]
    tp_state = sample["y_n_real_obs"] - y_eh_state
    Phi_state = np.asarray(baseline_state_var["Phi"], dtype=float)
    y1_idx = int(baseline_state_var["y1_index"])
    rows.append({
        "label": "baseline_state_var",
        "estimator": "state_var",
        "sample_start": baseline_state_var["sample_start"],
        "sample_end": baseline_state_var["sample_end"],
        "nobs": baseline_state_var["nobs"],
        "mu": np.asarray(baseline_state_var["z_bar"], dtype=float)[y1_idx],
        "rho": Phi_state[y1_idx, y1_idx],
        "intercept": np.asarray(baseline_state_var["const"], dtype=float)[y1_idx],
        "sigma": np.sqrt(np.asarray(baseline_state_var["Sigma"], dtype=float)[y1_idx, y1_idx]),
        "eh_multiplier": float("nan"),
        "max_abs_eig": baseline_state_var["max_abs_eig"],
        "mean_eh_spread": float(eh_spread_state.mean()),
        "std_eh_spread": float(eh_spread_state.std(ddof=1)),
        "mean_abs_eh_spread": float(eh_spread_state.abs().mean()),
        "max_abs_eh_spread": float(eh_spread_state.abs().max()),
        "mean_term_prem": float(tp_state.mean()),
        "std_term_prem": float(tp_state.std(ddof=1)),
    })

    rules: list[tuple[str, dict[str, float]]] = [
        ("ar1_mean_pinned", fit_short_rate_ar1(sample["y_1"])),
        ("ar1_ols_full_sample", fit_short_rate_ar1(sample["y_1"], mean_pinned=False)),
    ]

    post1980 = sample.loc[1980:SAMPLE_END, "y_1"].dropna()
    if len(post1980) >= 5:
        rules.append(("ar1_mean_pinned_post1980", fit_short_rate_ar1(post1980)))

    for rho in sensitivity_rhos:
        rules.append((f"fixed_rho_{theta_label(rho)}", fixed_rho_short_rate_ar1(sample["y_1"], rho)))

    for label, rule in rules:
        y_eh = expected_average_short_rate(sample["y_1"], rule, N_BOND)
        eh_spread = y_eh - sample["y_1"]
        tp = sample["y_n_real_obs"] - y_eh
        rows.append({
            "label": label,
            "estimator": rule["estimator"],
            "sample_start": rule["sample_start"],
            "sample_end": rule["sample_end"],
            "nobs": rule["nobs"],
            "mu": rule["mu"],
            "rho": rule["rho"],
            "intercept": rule["intercept"],
            "sigma": rule["sigma"],
            "eh_multiplier": rule["eh_multiplier"],
            "max_abs_eig": float("nan"),
            "mean_eh_spread": float(eh_spread.mean()),
            "std_eh_spread": float(eh_spread.std(ddof=1)),
            "mean_abs_eh_spread": float(eh_spread.abs().mean()),
            "max_abs_eh_spread": float(eh_spread.abs().max()),
            "mean_term_prem": float(tp.mean()),
            "std_term_prem": float(tp.std(ddof=1)),
        })
    return pd.DataFrame(rows)


def build_theta_dataset(
    full: pd.DataFrame,
    theta: float,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Build one theta-specific VAR dataset and diagnostic table."""
    y_theta = full["y_n_real_EH"] + theta * full["term_prem"]
    r_theta, duration_theta = constant_maturity_return_from_log_yield(y_theta, N_BOND)

    diag = pd.DataFrame(index=full.index)
    diag["theta"] = theta
    diag["y_1"] = full["y_1"]
    diag["y_n_real_obs"] = full["y_n_real_obs"]
    diag["y_n_real_EH"] = full["y_n_real_EH"]
    diag["term_prem"] = full["term_prem"]
    diag["y_n_real_theta"] = y_theta
    diag["spr_theta"] = y_theta - full["y_1"]
    diag["r_n_real_theta"] = r_theta
    diag["duration_theta"] = duration_theta
    diag["xb_theta"] = r_theta - full["y_1"].shift(1)

    out = pd.DataFrame(
        {
            "cape": full["cape"],
            "spr": diag["spr_theta"],
            "y_1": full["y_1"],
            "xr": full["xr"],
            "xb": diag["xb_theta"],
        },
        index=full.index,
    )
    out = out.loc[SAMPLE_START:SAMPLE_END].dropna()
    out.index.name = "year"
    diag = diag.loc[out.index].copy()
    diag.index.name = "year"
    return out, diag


def summarize_theta(theta: float, out: pd.DataFrame, diag: pd.DataFrame) -> dict[str, float]:
    """Moment summary for one theta dataset."""
    xb_jmean, xb_sd, xb_sharpe = sharpe_jensen(out["xb"])
    xr_jmean, xr_sd, xr_sharpe = sharpe_jensen(out["xr"])
    return {
        "theta": theta,
        "T": float(len(out)),
        "mean_y_10": float(diag["y_n_real_theta"].mean()),
        "std_y_10": float(diag["y_n_real_theta"].std(ddof=1)),
        "mean_spr": float(out["spr"].mean()),
        "std_spr": float(out["spr"].std(ddof=1)),
        "mean_xb": float(out["xb"].mean()),
        "std_xb": float(out["xb"].std(ddof=1)),
        "jensen_mean_xb": xb_jmean,
        "sharpe_xb": xb_sharpe,
        "jensen_mean_xr": xr_jmean,
        "std_xr": xr_sd,
        "sharpe_xr": xr_sharpe,
    }


def theta_one_max_abs_diff(theta_outputs: dict[float, pd.DataFrame]) -> float | None:
    """Check that theta=1 reproduces the active baseline dataset."""
    theta_one = None
    for theta, out in theta_outputs.items():
        if abs(theta - 1.0) < 1e-12:
            theta_one = out
            break
    if theta_one is None:
        return None

    active_out, _active_diag, _active_ar1 = build_active_baseline(return_diag=True)
    active_out.index.name = "year"
    aligned = theta_one[active_out.columns].loc[active_out.index]
    return float((aligned - active_out).abs().max().max())


def write_outputs(
    thetas: list[float],
    out_dir: Path,
    sensitivity_rhos: tuple[float, ...] = DEFAULT_SENSITIVITY_RHOS,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, float | None]:
    full, inflation_ar1, state_var = build_full_yield_table()
    out_dir.mkdir(parents=True, exist_ok=True)

    components = full.loc[SAMPLE_START:SAMPLE_END, [
        "y_1",
        "y_n_real_obs",
        "y_n_real_EH",
        "term_prem",
    ]].copy()
    y1_idx = int(state_var["y1_index"])
    components["eh_method"] = state_var["method"]
    components["state_var_y1_mean"] = np.asarray(state_var["z_bar"], dtype=float)[y1_idx]
    components["state_var_y1_lag_coeff"] = np.asarray(state_var["Phi"], dtype=float)[y1_idx, y1_idx]
    components["state_var_max_abs_eig"] = state_var["max_abs_eig"]
    components["infl_ar1_mu"] = inflation_ar1["mu"]
    components["infl_ar1_phi"] = inflation_ar1["phi"]
    components["eh_spread"] = components["y_n_real_EH"] - components["y_1"]
    components.index.name = "year"
    components.to_csv(out_dir / "term_premium_components.csv")

    sensitivity = short_rate_sensitivity_table(
        full, state_var, tuple(float(x) for x in sensitivity_rhos)
    )
    sensitivity.to_csv(out_dir / "short_rate_sensitivity.csv", index=False)

    theta_outputs: dict[float, pd.DataFrame] = {}
    all_diag = []
    moments = []
    for theta in thetas:
        out, diag = build_theta_dataset(full, theta)
        if len(out) != SAMPLE_END - SAMPLE_START + 1:
            raise RuntimeError(
                f"theta={theta} produced T={len(out)}, expected "
                f"{SAMPLE_END - SAMPLE_START + 1}"
            )
        label = theta_label(theta)
        out.to_csv(out_dir / f"var_dataset_theta_{label}.csv")
        diag_for_stack = diag.reset_index()
        all_diag.append(diag_for_stack)
        moments.append(summarize_theta(theta, out, diag))
        theta_outputs[theta] = out

    diagnostics = pd.concat(all_diag, ignore_index=True)
    diagnostics.to_csv(out_dir / "term_premium_scaling_diagnostics.csv", index=False)

    moments_df = pd.DataFrame(moments)
    theta_one_diff = theta_one_max_abs_diff(theta_outputs)
    if theta_one_diff is not None:
        if theta_one_diff >= 1e-10:
            raise RuntimeError(
                "theta=1 should reproduce the active baseline; "
                f"max abs diff was {theta_one_diff:.3e}"
            )
        moments_df["theta_1_max_abs_diff_vs_active"] = theta_one_diff
    moments_df.to_csv(out_dir / "term_premium_scaling_moments.csv", index=False)

    return moments_df, components, sensitivity, theta_one_diff


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build theta-scaled real term-premium VAR datasets."
    )
    parser.add_argument(
        "--theta",
        nargs="*",
        type=float,
        default=list(DEFAULT_THETAS),
        help="Theta values to build. Default: 0 0.25 0.5 0.75 1.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=OUT_DIR,
        help="Output directory. Default: data/term_premium_scaling.",
    )
    parser.add_argument(
        "--sensitivity-rho",
        nargs="*",
        type=float,
        default=list(DEFAULT_SENSITIVITY_RHOS),
        help="Fixed rho values for short-rate sensitivity diagnostics.",
    )
    args = parser.parse_args()

    thetas = sorted(dict.fromkeys(float(x) for x in args.theta))
    moments, components, sensitivity, theta_one_diff = write_outputs(
        thetas,
        args.out_dir,
        sensitivity_rhos=tuple(float(x) for x in args.sensitivity_rho),
    )

    full, _inflation_ar1, state_var = build_full_yield_table()
    tp = full.loc[SAMPLE_START:SAMPLE_END, "term_prem"].dropna()
    eh_spread = (
        full.loc[SAMPLE_START:SAMPLE_END, "y_n_real_EH"]
        - full.loc[SAMPLE_START:SAMPLE_END, "y_1"]
    ).dropna()

    print("=" * 78)
    print("TERM-PREMIUM SCALING COUNTERFACTUALS")
    print("=" * 78)
    print(f"Sample: {SAMPLE_START}-{SAMPLE_END}, T={SAMPLE_END - SAMPLE_START + 1}")
    print(f"Maturity: n={N_BOND}")
    print()
    Phi_state = np.asarray(state_var["Phi"], dtype=float)
    const_state = np.asarray(state_var["const"], dtype=float)
